'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const js=fs.readFileSync('app/static/app.js','utf8');
const start=js.indexOf('function canManageAudit(a)');
const end=js.indexOf('async function renderAudits(){',start);
assert.ok(start>=0&&end>start);
const context={S:{user:{id:7,role:'reviewer'}},aButton:(label,act,extra)=>`<button data-act="${act}" ${extra}>${label}</button>`};
vm.createContext(context);
vm.runInContext(js.slice(start,end),context);
let owner={id:21,created_by:7,status:'complete'};
let buttons=vm.runInContext('reportActions('+JSON.stringify(owner)+')',context);
assert.match(buttons,/data-act="rerun-audit"/);
assert.match(buttons,/data-act="delete-audit"/);
assert.match(buttons,/data-act="open-audit"/);
buttons=vm.runInContext('reportActions('+JSON.stringify({...owner,created_by:8})+')',context);
assert.doesNotMatch(buttons,/data-act="rerun-audit"|data-act="delete-audit"/);
buttons=vm.runInContext('reportActions('+JSON.stringify({...owner,status:'running'})+')',context);
assert.doesNotMatch(buttons,/data-act="rerun-audit"|data-act="delete-audit"/);
context.S.user.role='admin';
buttons=vm.runInContext('reportActions('+JSON.stringify({...owner,created_by:8})+')',context);
assert.match(buttons,/data-act="rerun-audit"/);
assert.match(buttons,/data-act="delete-audit"/);
assert.match(js,/\/api\/audits\/\$\{id\}\/rerun/);
assert.match(js,/\/api\/audits\/\$\{id\}.*method:'DELETE'/s);
console.log('Rerun/delete UI actions and ownership rules OK');
