'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assets=path.join(__dirname,'../app/static');
const app=fs.readFileSync(path.join(assets,'app.js'),'utf8');
const css=fs.readFileSync(path.join(assets,'app.css'),'utf8');
const html=fs.readFileSync(path.join(assets,'index.html'),'utf8');
const theme=fs.readFileSync(path.join(assets,'theme.js'),'utf8');
assert.match(app,/page-actions/);
assert.match(app,/table-actions/);
assert.match(app,/id="theme-preference"/);
assert.match(app,/SyllabusTheme.setPreference\(e.target.value\)/);
assert.match(css,/\.page-actions \.btn \{ min-height: 40px; height: 40px;/);
assert.match(css,/\.table-actions \.btn \{ min-height: 33px; height: 33px;/);
assert.match(css,/\[data-theme="dark"\] \.panel/);
assert.match(html,/<script src="\/assets\/theme.js"><\/script>/);

// Test the browser-local preference and system change handler without an AI or web server.
let stored=new Map(),isDark=false,listener;
const root={attributes:{},style:{},setAttribute(key,v){this.attributes[key]=v;}};
const meta={content:'#fff'};
const media={get matches(){return isDark},addEventListener(_event,callback){listener=callback}};
const window={matchMedia:()=>media,localStorage:{getItem:k=>stored.get(k)||null,setItem:(k,v)=>stored.set(k,v)}};
const context={window,document:{documentElement:root,querySelector:()=>meta},Set};
vm.createContext(context);vm.runInContext(theme,context);
assert.equal(root.attributes['data-theme'],'light');
window.SyllabusTheme.setPreference('dark');
assert.equal(root.attributes['data-theme'],'dark');
assert.equal(window.SyllabusTheme.getPreference(),'dark');
isDark=false;listener();assert.equal(root.attributes['data-theme'],'dark');
window.SyllabusTheme.setPreference('system');
assert.equal(root.attributes['data-theme'],'light');
isDark=true;listener();assert.equal(root.attributes['data-theme'],'dark');
isDark=false;listener();assert.equal(root.attributes['data-theme'],'light');
window.SyllabusTheme.setPreference('light');
isDark=true;listener();assert.equal(root.attributes['data-theme'],'light');
assert.equal(meta.content,'#ffffff');
console.log('PASS theme preference, system switching, page/row button classes and HTML asset loading');
